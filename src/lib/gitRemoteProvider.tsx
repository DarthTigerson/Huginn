export type GitRemoteProvider = 'github' | 'gitlab' | 'bitbucket' | 'other'

// Substring match (not an exact-host allowlist) so self-hosted GitHub
// Enterprise / GitLab instances (e.g. "github.mycorp.internal") still pick up
// their brand icon, not just the public github.com/gitlab.com domains.
export function detectGitRemoteProvider(url: string): GitRemoteProvider {
  let hostname: string
  try {
    hostname = new URL(url).hostname.toLowerCase()
  } catch {
    return 'other'
  }
  if (hostname.includes('github')) return 'github'
  if (hostname.includes('gitlab')) return 'gitlab'
  if (hostname.includes('bitbucket')) return 'bitbucket'
  return 'other'
}


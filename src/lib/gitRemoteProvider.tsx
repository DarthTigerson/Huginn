export function gitRemoteIcon(provider: GitRemoteProvider) {
  switch (provider) {
    case 'github': return <GitHubIcon />
    case 'gitlab': return <GitLabIcon />
    case 'bitbucket': return <BitbucketIcon />
    case 'other': return <OtherGitRemoteIcon />
  }
}

export function gitRemoteLabel(provider: GitRemoteProvider): string {
  switch (provider) {
    case 'github': return 'Open GitHub'
    case 'gitlab': return 'Open GitLab'
    case 'bitbucket': return 'Open Bitbucket'
    case 'other': return 'Open Repository'
  }
}
